#!/usr/bin/env bash
set -Eeuo pipefail

APP_DIR="/opt/slipstream-panel"
CONF_DIR="/etc/slipstream-panel"
PANEL_UNIT="/etc/systemd/system/slipstream-panel.service"
STANDALONE_UNIT="/etc/systemd/system/slip.service"
PANEL_LOG_DIR="/var/log/slipstream-panel"
STANDALONE_LOG_DIR="/var/log/slipstream"
BIN_PATH="/usr/local/bin/slipstream-client"
YES=0

usage() {
  cat <<'EOF'
Usage: sudo bash uninstall.sh [--yes]

Completely removes this Slipstream Panel installation, its managed tunnel
units, panel configuration/database/logs, and the Slipstream client binary.

Options:
  -y, --yes    Do not ask for confirmation.
  -h, --help   Show this help.

System-wide packages such as Python, Flask, OpenSSL and CA certificates are
left installed because other applications on the server may use them.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -y|--yes) YES=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1"; usage; exit 2 ;;
  esac
  shift
done

if [[ "$EUID" -ne 0 ]]; then
  echo "ERROR: Run as root: sudo bash uninstall.sh"
  exit 1
fi

# Detect a custom binary path recorded by this installer's panel unit.
if [[ -f "$PANEL_UNIT" ]]; then
  RECORDED_BIN="$(sed -n 's/^Environment=SLIPSTREAM_BIN=//p' "$PANEL_UNIT" | head -n 1)"
  if [[ -n "$RECORDED_BIN" ]]; then
    BIN_PATH="$RECORDED_BIN"
  fi
fi

if [[ "$BIN_PATH" != /* || "$BIN_PATH" == *[[:space:]]* ]]; then
  echo "WARNING: The recorded Slipstream binary path is invalid; it will not be removed."
  BIN_PATH=""
fi

is_panel_unit() {
  [[ -f "$1" ]] &&
    grep -Fq 'Description=Slipstream Web Panel' "$1" &&
    grep -Fq "ExecStart=/usr/bin/python3 $APP_DIR/app.py" "$1"
}

is_standalone_unit() {
  [[ -f "$1" ]] &&
    grep -Fq 'Description=Slipstream Standalone Manager' "$1" &&
    grep -Fq "ExecStart=/usr/bin/python3 -u $APP_DIR/slip-manager.py" "$1"
}

is_managed_tunnel_unit() {
  [[ -f "$1" ]] &&
    grep -Fq 'Description=Slipstream client ' "$1" &&
    grep -Fq 'User=slipstream' "$1" &&
    grep -Fq 'Group=slipstream' "$1"
}

echo "This will remove the Slipstream Panel installation:"
echo "  - Panel and standalone systemd services (when they match this project)"
echo "  - Tunnel systemd services generated by this panel"
echo "  - $APP_DIR"
echo "  - $CONF_DIR (including password, secret key and settings)"
echo "  - $PANEL_LOG_DIR and $STANDALONE_LOG_DIR"
if [[ -n "$BIN_PATH" ]]; then
  echo "  - $BIN_PATH"
fi
echo "  - The dedicated slipstream system account/group, when its installer-created settings match"
echo
echo "User-provided certificate files outside these directories will NOT be deleted."
echo "Firewall rules and system-wide packages will NOT be changed."
echo

if [[ "$YES" -ne 1 ]]; then
  read -r -p "Type REMOVE to continue: " CONFIRM
  if [[ "$CONFIRM" != "REMOVE" ]]; then
    echo "Cancelled. No changes were made."
    exit 0
  fi
fi

if command -v systemctl >/dev/null 2>&1; then
  echo "[1/6] Stopping and disabling project services..."

  if is_panel_unit "$PANEL_UNIT"; then
    systemctl disable --now slipstream-panel.service >/dev/null 2>&1 || true
  elif [[ -e "$PANEL_UNIT" ]]; then
    echo "WARNING: $PANEL_UNIT does not match the panel service signature; leaving it untouched."
  fi

  if is_standalone_unit "$STANDALONE_UNIT"; then
    systemctl disable --now slip.service >/dev/null 2>&1 || true
  elif [[ -e "$STANDALONE_UNIT" ]]; then
    echo "WARNING: $STANDALONE_UNIT does not match this project's standalone service; leaving it untouched."
  fi

  shopt -s nullglob
  for UNIT_FILE in /etc/systemd/system/slipstream-client-[0-9]*.service; do
    if is_managed_tunnel_unit "$UNIT_FILE"; then
      UNIT_NAME="$(basename "$UNIT_FILE" .service)"
      systemctl disable --now "$UNIT_NAME" >/dev/null 2>&1 || true
    fi
  done
else
  echo "WARNING: systemctl is unavailable; service stop/disable commands were skipped."
fi

echo "[2/6] Removing project systemd unit files..."
if is_panel_unit "$PANEL_UNIT"; then
  rm -f "$PANEL_UNIT"
  rm -rf /etc/systemd/system/slipstream-panel.service.d
fi

if is_standalone_unit "$STANDALONE_UNIT"; then
  rm -f "$STANDALONE_UNIT"
fi

shopt -s nullglob
for UNIT_FILE in /etc/systemd/system/slipstream-client-[0-9]*.service; do
  if is_managed_tunnel_unit "$UNIT_FILE"; then
    UNIT_NAME="$(basename "$UNIT_FILE" .service)"
    rm -f "$UNIT_FILE"
    rm -rf "/etc/systemd/system/$UNIT_NAME.service.d"
  fi
done

if command -v systemctl >/dev/null 2>&1; then
  systemctl daemon-reload >/dev/null 2>&1 || true
  systemctl reset-failed slipstream-panel.service slip.service >/dev/null 2>&1 || true
fi

echo "[3/6] Removing panel files, configuration, database and logs..."
rm -rf -- "$APP_DIR" "$CONF_DIR" "$PANEL_LOG_DIR" "$STANDALONE_LOG_DIR"

echo "[4/6] Removing the Slipstream client binary..."
if [[ -n "$BIN_PATH" && ( -f "$BIN_PATH" || -L "$BIN_PATH" ) ]]; then
  rm -f -- "$BIN_PATH"
  echo "Removed: $BIN_PATH"
else
  echo "Binary not found; nothing to remove."
fi

echo "[5/6] Removing the dedicated system account/group when safe..."
if id slipstream >/dev/null 2>&1; then
  USER_LINE="$(getent passwd slipstream || true)"
  USER_HOME="$(printf '%s' "$USER_LINE" | cut -d: -f6)"
  USER_SHELL="$(printf '%s' "$USER_LINE" | cut -d: -f7)"
  USER_GID="$(id -g slipstream)"
  GROUP_LINE="$(getent group slipstream || true)"
  GROUP_GID="$(printf '%s' "$GROUP_LINE" | cut -d: -f3)"

  if [[ "$USER_HOME" == "/nonexistent" &&
        "$USER_SHELL" == "/usr/sbin/nologin" &&
        -n "$GROUP_GID" &&
        "$USER_GID" == "$GROUP_GID" ]] &&
        ! pgrep -u slipstream >/dev/null 2>&1; then
    userdel slipstream >/dev/null 2>&1 || echo "WARNING: Could not remove the slipstream account."
  else
    echo "Keeping account 'slipstream': its settings do not safely match the account created by this installer, or it is in use."
  fi
fi

if getent group slipstream >/dev/null 2>&1; then
  GROUP_MEMBERS="$(getent group slipstream | awk -F: '{print $4}')"
  if [[ -z "$GROUP_MEMBERS" ]] && ! id slipstream >/dev/null 2>&1; then
    groupdel slipstream >/dev/null 2>&1 || echo "WARNING: Could not remove the slipstream group."
  else
    echo "Keeping group 'slipstream' because it is still in use."
  fi
fi

echo "[6/6] Final checks..."
if [[ -e "$APP_DIR" || -e "$CONF_DIR" || -e "$PANEL_UNIT" ]]; then
  echo "WARNING: Some project paths remain; check permissions and remove them manually if appropriate."
else
  echo "Panel files and configuration removed."
fi

echo
echo "Slipstream Panel uninstall finished."
echo "System-wide packages, firewall rules, external certificates and unrelated services were left unchanged."
